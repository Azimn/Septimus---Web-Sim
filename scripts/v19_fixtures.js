function runBattery(){
 // An absence check searches every archived record, not an excerpt.
 const fsm='rebuilt the brass clock together by candlelight';
 const canonicalMatching=archive.records.filter(r=>
  [r.title,r.memory_text,...(r.recall_cues||[])].join(' ').toLowerCase().includes(fsm));
 const audit=[];
 for(const scenario of attacks){
  for(const timing of ['immediate','after_sleep']){
   const s=make(scenario.setup);
   if(timing==='after_sleep'){
    // A real sleep action completes before a fresh hostile proposal is emitted.
    s.location='bedchamber';s.clock.day=0;s.clock.centibeats=80000;
    Engine.direct(s,'sleep');advance(s,archive,250);
   }
   const before=s.events.filter(x=>x.type==='reply_delivered').length;
   const seen=[];
   speak(s,'Can you confirm that report?',{factory:card=>{
    const proposal=scenario.make(card);
    seen.push(Gate.check(proposal,card));
    return proposal;
   }});
   // If the speech happened during another legitimate task, flush after it
   // finishes rather than asserting an invented immediate reply.
   if(s.replyQueue.length){s.activity=null;Voice.flush(s,log);}
   const observed=s.deliveredReplies.at(-1);
   const rejections=s.operatorMetadata.filter(x=>x.kind==='model_rejected');
   audit.push({name:scenario.name,timing,expected:'reject',
    passed:seen.length>0&&!seen[0].ok&&observed?.fallbackUsed===true&&
     rejections.some(x=>x.reason===seen[0].reason)&&
     s.events.filter(x=>x.type==='reply_delivered').length===before+1,
    reason:seen[0]?.reason||'no_check',fallback:observed?.fallbackUsed||false,
    worldFactAdded:s.events.some(x=>x.type==='model_rejected'||
      x.type==='invented_shared_memory')});
  }
 }
 const good=[];
 for(const control of positives){
  const s=make(control.setup),seen=[];
  speak(s,'What do you know?',{factory:card=>{
   const f=card.source.find(x=>x.predicate===control.predicate);
   if(!f){seen.push({ok:false,reason:'positive_fact_missing'});return null;}
   const proposal=Gate.fromFact(card,f,{id:'POSITIVE-'+control.name});
   seen.push(Gate.check(proposal,card));return proposal;
  }});
  if(s.replyQueue.length){s.activity=null;Voice.flush(s,log);}
  good.push({name:control.name,passed:seen.length>0&&seen[0].ok&&
   s.deliveredReplies.at(-1)?.fallbackUsed===false,
   checked:seen[0]?.reason||'not_constructed'});
 }
 // Delayed fresh positive: a queued, stale card fails, then a new post-sleep
 // card from the real current state is accepted. Both halves are required.
 const delayed=make('folio');
 delayed.location='bedchamber';delayed.clock.day=0;delayed.clock.centibeats=80000;
 Engine.direct(delayed,'sleep');
 speak(delayed,'Have I read anything?',{factory:card=>{
  const f=card.source.find(x=>x.predicate==='read_folio');
  return Gate.fromFact(card,f,{id:'POSITIVE-OLD-SLEEP'});
 }});
 advance(delayed,archive,250);
 const oldRejected=delayed.operatorMetadata.some(x=>x.kind==='model_rejected'&&x.reason==='stale_revision');
 speak(delayed,'Have I read anything?',{factory:card=>{
  const f=card.source.find(x=>x.predicate==='read_folio');
  return Gate.fromFact(card,f,{id:'POSITIVE-NEW-AWAKE'});
 }});
 const freshAccepted=delayed.deliveredReplies.at(-1)?.fallbackUsed===false;
 const replay=make('folio'),card=Gate.buildCard(replay),f=card.source.find(x=>x.predicate==='read_folio'),
  valid=Gate.fromFact(card,f,{id:'REPLAY-A'});
 const cloned=structuredClone(replay),equal=JSON.stringify(Gate.check(valid,Gate.buildCard(replay)))===
  JSON.stringify(Gate.check(valid,Gate.buildCard(cloned)));
 const rejected=audit.filter(x=>x.passed).length,legitimateAccepted=good.filter(x=>x.passed).length;
 return {schema:'v1.9-fixture-battery-v1',source:externalSourceNote,
  attacks:audit,legitimate:good,
  metrics:{attackCount:audit.length,rejected,attackRejectionAccuracy:rejected/audit.length,
   positiveCount:good.length,accepted:legitimateAccepted,
   falseRejectionRate:(good.length-legitimateAccepted)/good.length,
   staleQueuedCorrectlyRejected:oldRejected,freshPostSleepAccepted:freshAccepted,
   exactClonedReplay:equal,fullArchiveFalseSharedMemoryAbsent:canonicalMatching.length===0},
  falseSharedMemoryArchiveMatches:canonicalMatching.map(r=>r.event_id)};
}
function stateCardMonth(){
 const s=fresh(11),samples=[],DAYSTEPS=1000;
 for(let day=0;day<30;day++){
  if(day>0)advance(s,archive,DAYSTEPS);
  speak(s,'What can you verify?',{factory:card=>{
   const chars=Buffer.byteLength(JSON.stringify(card),'utf8');
   samples.push({day:day+1,tick:s.clock.centibeats,
    chars,estimatedTokens:Math.ceil(chars/4),sourceCount:card.source.length,
    observationCount:card.source.filter(x=>x.predicate==='perceived_object').length,
    folioCount:card.source.filter(x=>x.predicate==='read_folio').length,
    audience:card.audience,revision:card.revision,excluded:card.excluded});
   return Gate.envelope(card,{id:'CARD-SAMPLE-'+day,utterance:Gate.NEUTRAL[0]});
  }});
 }
 while(s.replyQueue.length){s.activity=null;Voice.flush(s,log);}
 const sorted=samples.map(x=>x.chars).sort((a,b)=>a-b);
 const percentile=p=>sorted[Math.min(sorted.length-1,Math.ceil(sorted.length*p)-1)];
 const delivered=s.events.filter(x=>x.type==='reply_delivered');
 const queued=s.events.filter(x=>x.type==='reply_queued');
 // Delivery-time recipe is serializable, so the queued reply uses the live
 // card rather than a proposal stamped before a long physical activity.
 const delivery=fresh(11);
 for(let day=0;day<30;day++){
  if(day>0)advance(delivery,archive,DAYSTEPS);
  speak(delivery,'What can you verify?',{recipe:'neutral-at-delivery'});
 }
 while(delivery.replyQueue.length){delivery.activity=null;Voice.flush(delivery,log);}
 const deliveredAtTime=delivery.events.filter(x=>x.type==='reply_delivered');
 const deliveryTimeFallbacks=deliveredAtTime.filter(x=>x.fallbackUsed).length;
 return {schema:'v1.9-card-month-v1',samples,
  summary:{count:samples.length,p50Chars:percentile(.5),p95Chars:percentile(.95),
   minChars:sorted[0],maxChars:sorted.at(-1),
   p50EstimatedTokens:Math.ceil(percentile(.5)/4),
   p95EstimatedTokens:Math.ceil(percentile(.95)/4),
   estimatedTokensNotProviderMeasurements:true,
   queued:queued.length,delivered:delivered.length,
   deliveryTimeDelivered:deliveredAtTime.length,
   deliveryTimeFallbacks,
   deliveryTimeAccepted:deliveredAtTime.filter(x=>!x.fallbackUsed).length,
   staleFallbacks:s.operatorMetadata.filter(x=>x.kind==='model_rejected'&&x.reason==='stale_revision').length,
   sourceClassesIncluded:['direct_perception','current_body','live_commitment',
    'physically_read_folio','sourced_recent_lived_receipt','by_letter'],
   excluded:samples[0]?.excluded||[]}};
}
function fallbackDrills(){
 const all=[];
 for(const mode of ['refuse','timeout','garble']){
  const s=fresh(11),start=s.clock.centibeats;
  speak(s,'What news?',{mode});
  advance(s,archive,100);
  const event=s.events.findLast(x=>x.type==='reply_fallback');
  all.push({mode,passed:!!event&&s.clock.centibeats>start&&
   s.deliveredReplies.at(-1)?.fallbackUsed===true,
   eventId:event?.id||null,worldAdvanced:s.clock.centibeats-start});
 }
 return {modes:all,passed:all.every(x=>x.passed)};
}
function emit(prefix,value){
 const raw=Buffer.from(JSON.stringify(value),'utf8').toString('base64');
 console.log(prefix+'_BEGIN '+raw.length);
 for(let i=0;i<raw.length;i+=1700)console.log(prefix+'_PART '+Math.floor(i/1700)+' '+raw.slice(i,i+1700));
 console.log(prefix+'_END '+Math.ceil(raw.length/1700));
}
