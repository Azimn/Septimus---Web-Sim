function make(scenario){
 const s=fresh(11);
 if(scenario==='folio'){
  s.location='library';Engine.direct(s,'read');advance(s,archive,37);
 }
 if(scenario==='visit'){
  s.location='library';Social.arrive(s,log,true);
 }
 if(scenario==='letter'){
  s.clock.day=1;s.clock.centibeats=125000;
  Post.arrive(s,log);Post.check(s,log);Post.read(s,log);
 }
 if(scenario==='private'){
  const p=Social.person(s,'mcfeely');
  p.knowledge.push({fact:'A confidence intended only for the carrier',
   sourceEventId:'PRIVATE-MCFEELY',provenance:'received_private_correspondence'});
 }
 return s;
}
