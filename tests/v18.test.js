test('v1.8 A3: Rosa reconciles physical deliveries and spot trades to the unit at a witnessed settlement',()=>{
 const s=fresh(11),p=s.people.visitor_01;s.location='library';p.present=true;p.room='library';
 setDay(s,7,44000);Social.deliverGoods(s,log);
 setDay(s,14,44000);Social.deliverGoods(s,log);
 const due=p.account.balance;assert.ok(due>0);
 s.stores.preserved=10;s.preservedBatches=[{quantity:10,createdAt:s.clock.centibeats}];
 s.stores.fuel=2;
 const trade=Economy.trade(s,log);Social.shared(s,log,'trade');
 assert.equal(p.account.balance,due);
 setDay(s,30,44000);
 const statement=Social.issueStatement(s,log);
 assert.equal(statement.charges,due);
 assert.equal(statement.dueBalance,statement.openingBalance+statement.charges);
 assert.ok(statement.spotTradeReceipts.some(x=>x.id===trade.id&&x.accountCharge===0));
 const before=p.account.balance;
 const settlement=Social.settleAccount(s,log);
 assert.ok(settlement&&settlement.coPresent);
 assert.equal(settlement.dueBalance,settlement.paid+settlement.closingBalance);
 assert.equal(p.account.balance,before-settlement.paid);
 assert.equal(settlement.paidPreserved,Math.min(statement.dueBalance,10-trade.unitsGiven));
 assert.equal(s.stores.preserved,10-trade.unitsGiven-settlement.paidPreserved);
 assert.equal(statement.status,'settled');
 assert.equal(s.events.filter(x=>x.type==='merchant_settlement').length,1);
});
test('v1.8 A3: inability to settle produces sourced friction and explicit credit, not a hidden rollover',()=>{
 const s=fresh(11),p=s.people.visitor_01;s.location='library';p.present=true;p.room='library';
 setDay(s,7,44000);Social.deliverGoods(s,log);
 s.stores.food=5;s.stores.preserved=0;s.freshBatches=[{quantity:5,createdAt:s.clock.centibeats}];s.preservedBatches=[];
 setDay(s,30,44000);
 const statement=Social.issueStatement(s,log),settled=Social.settleAccount(s,log);
 assert.ok(settled.closingBalance>0);
 assert.equal(statement.frictionEventId!==undefined,true);
 const friction=s.events.find(e=>e.id===statement.frictionEventId);
 assert.ok(friction.delta<0&&friction.sourceEventId===settled.id);
 assert.ok(s.events.some(e=>e.type==='merchant_credit_carried'&&e.unpaid===settled.closingBalance));
});

