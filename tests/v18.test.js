'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {fresh}=require('../scripts/v12_probe');
const {log}=require('../src/engine');
const C=require('../src/commitments');
const Social=require('../src/social'),Economy=require('../src/economy'),Cognition=require('../src/cognition');
const DAY=100000;
function setDay(s,day,phase=25000){s.clock.day=day;s.clock.centibeats=day*DAY+phase;}
test('v1.8 A1: three consecutive months generated by runtime interval rules, with sibling links and distinct receipts',()=>{
 const s=fresh(11);
 for(const d of [8,16,23,38,46,53,68,76,83]){setDay(s,d);C.scheduleMonth(s,log);}
 const events=s.events.filter(e=>e.type==='series_instance_generated');
 assert.equal(events.length,9);
 assert.equal(new Set(events.map(x=>x.instanceId)).size,9);
 for(const id of ['MONTH-FOLIO','MONTH-INSTRUMENT','MONTH-PROVISIONS']){
  assert.deepEqual(C.ledger(s,id).instances,[id,id+'@02',id+'@03']);
  const chain=events.filter(e=>e.seriesId===id);
  assert.deepEqual(chain.map(e=>e.ordinal),[1,2,3]);
  assert.ok(chain.every(e=>e.rule.intervalDays===30&&e.deadline===
   ((e.ordinal-1)*30+e.rule.dueOffset)*DAY+65000));
  assert.equal(chain[2].previousInstanceId,chain[1].instanceId);
 }
});
test('v1.8 A2: a broken monthly instance does not cancel the next, and a still-open predecessor is superseded',()=>{
 const s=fresh(11);
 setDay(s,23);C.scheduleMonth(s,log);
 const first=s.commitments.find(c=>c.id==='MONTH-PROVISIONS');
 setDay(s,53);C.scheduleMonth(s,log);
 assert.equal(first.status,'broken');assert.equal(first.breakCause,'superseded_by_MONTH-PROVISIONS@02');
 const second=s.commitments.find(c=>c.id==='MONTH-PROVISIONS@02');
 assert.ok(second&&second.status==='open');
 C.breakInstance(s,second,log,'forced_plot_unavailable');
 setDay(s,83);C.scheduleMonth(s,log);
 assert.equal(s.commitments.find(c=>c.id==='MONTH-PROVISIONS@03').status,'open');
 assert.equal(C.ledger(s,'MONTH-PROVISIONS').broken,2);
 assert.equal(C.ledger(s,'MONTH-PROVISIONS').brokenStreak,2);
 assert.ok(s.events.some(e=>e.type==='commitment_superseded'&&e.predecessorId===first.id));
});
test('v1.8 A2: two consecutive failures enter self-sheet, rumination, and pressure without granting work',()=>{
 const s=fresh(11),base=fresh(11);
 setDay(s,23);C.scheduleMonth(s,log);
 const a=s.commitments.find(x=>x.id==='MONTH-PROVISIONS');C.breakInstance(s,a,log,'controlled_block');
 setDay(s,53);C.scheduleMonth(s,log);
 const b=s.commitments.find(x=>x.id==='MONTH-PROVISIONS@02');C.breakInstance(s,b,log,'controlled_block');
 setDay(s,83);C.scheduleMonth(s,log);
 // Keep the matched control's first two provisions commitments through
 // actual work so the comparison isolates the failures rather than missing time.
 setDay(base,23);C.scheduleMonth(base,log);
 base.stores.food=12;
 const firstBase=base.commitments.find(x=>x.id==='MONTH-PROVISIONS');
 C.completed(base,{kind:'tend',commitmentId:firstBase.id},log);
 C.completed(base,{kind:'tend',commitmentId:firstBase.id},log);
 setDay(base,53);C.scheduleMonth(base,log);
 const secondBase=base.commitments.find(x=>x.id==='MONTH-PROVISIONS@02');
 C.completed(base,{kind:'tend',commitmentId:secondBase.id},log);
 C.completed(base,{kind:'tend',commitmentId:secondBase.id},log);
 setDay(base,83);C.scheduleMonth(base,log);
 const open=s.commitments.find(x=>x.id==='MONTH-PROVISIONS@03');
 const regular=base.commitments.find(x=>x.id==='MONTH-PROVISIONS@03');
 assert.ok(Cognition.selfSheet(s).urgentSeries.some(x=>x.id==='MONTH-PROVISIONS'&&x.brokenStreak===2));
 assert.ok(!Cognition.selfSheet(base).urgentSeries.some(x=>x.id==='MONTH-PROVISIONS'));
 assert.ok(C.obligationPressure(s,open)>C.obligationPressure(base,regular));
 let failedReferences=0,controlReferences=0;
 for(let i=0;i<30;i++){
  const t=(Math.floor(83*DAY/4500)+i)*4500;
  s.clock.centibeats=t;base.clock.centibeats=t;
  const e=Cognition.ruminate(s,log),c=Cognition.ruminate(base,log);
  failedReferences+=Number(e?.seriesId==='MONTH-PROVISIONS');
  controlReferences+=Number(c?.seriesId==='MONTH-PROVISIONS');
 }
 assert.ok(failedReferences>=5,{failedReferences});
 assert.equal(controlReferences,0);
});
